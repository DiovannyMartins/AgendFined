note "Guardado em $ENV_FILE (server-only, nunca commite)."

# ── Stage 3: Webhook (URL de notificação + secret) ─────────────────────────
stage "Mercado Pago: Webhook (notificações de assinatura)"
say "Configura a URL de notificação e o evento de assinatura, e captura a secret da assinatura."
open_url "https://www.mercadopago.com.br/developers/panel/app"
step "Na aplicação, no menu à esquerda, clique em 'Webhooks > Configurar notificações'."
step "Em 'URL de modo de teste', cole: $NOTIFICATION_URL"
step "Marque o evento 'Plans and Subscriptions' → 'Subscription linking' (topic subscription_preapproval)."
step "Clique em 'Salvar'. Depois, em 'Webhooks > Configurar notificação', clique em revelar a assinatura (secret)."
ask_secret MERCADO_PAGO_WEBHOOK_SECRET "Cole a secret do webhook (x-signature):"
write_env MERCADO_PAGO_WEBHOOK_SECRET "$MERCADO_PAGO_WEBHOOK_SECRET"
note "Dica: use o botão 'Simular' para enviar um evento de teste à URL e confirmar a resposta 200."
note "Depois, rode: npm run dev e teste o upgrade no dashboard (Plano → Fazer upgrade)."

finish
