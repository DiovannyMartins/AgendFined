TOTAL_STAGES=3

banner "Mercado Pago (sandbox) — assinatura PROFISSIONAL"

# ── Stage 1: expor o app local via túnel (URL do webhook + back_url) ───────
stage "Túnel público (URL do webhook + back_url)"
say "O Mercado Pago precisa de uma URL HTTPS pública para o webhook da assinatura e para o back_url."
note "O back_url (para onde o pagador volta após o checkout) usa APP_URL, e o Mercado Pago rejeita localhost como URL."
note "Inicie um túnel para o app rodando em http://localhost:3000 e deixe-o aberto."
step "Em um outro terminal, rode: ngrok http 3000   (ou: cloudflared tunnel --url http://localhost:3000)"
step "Copie a URL HTTPS de encaminhamento (ex.: https://abc-123.ngrok-free.app)."
ask TUNNEL_URL "Cole a URL HTTPS do túnel (sem o caminho):"
TUNNEL_URL="${TUNNEL_URL%/}"
NOTIFICATION_URL="${TUNNEL_URL}/api/webhooks/mercadopago"
write_env MERCADO_PAGO_NOTIFICATION_URL "$NOTIFICATION_URL"
write_env APP_URL "$TUNNEL_URL"
note "URL de webhook registrada: $NOTIFICATION_URL"
note "APP_URL definido para $TUNNEL_URL (usado como back_url do preapproval)."
note "Mantenha o túnel rodando. Se reiniciar o túnel, a URL muda — rode este script de novo."

# ── Stage 2: Access Token (sandbox) ────────────────────────────────────────
stage "Mercado Pago: Access Token (teste)"
say "Crie a aplicação e copie o Access Token de teste (sandbox)."
note "Para assinaturas, se 'Test credentials' não aparecer, use as credenciais de um 'usuário de teste' (vendedor)."
open_url "https://www.mercadopago.com.br/developers/panel/app"
